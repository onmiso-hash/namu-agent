def 원문_판정(원문):
    """원문 한 건을 판정 함수에 넣어 '말로 반박'으로 잡힌 신호를 돌려준다. 못 잡으면 None."""
    세션 = {
        "발화": [("2026-01-01T00:00:00Z", 앞선_발화), ("2026-01-01T00:01:00Z", 원문)],
        "중단": [],
        "거절": [],
    }
    for 건 in naite.되돌림_찾기(세션):
        if 건["갈래"] == "말로 반박" and 건["글"] == 원문:
            return 건["신호"]
    return None


def 그날_기록(날짜):
    """(그날 사람 발화가 있었나, 그날 잡힌 것 목록). 대화 기록에서 찾는다."""
    있었나 = False
    잡힌것 = []
    for 파일 in naite.대화_기록_파일들():
        세션 = naite.세션_읽기(파일)
        if any(_우리날짜(시각) == 날짜 for 시각, _ in 세션["발화"]):
            있었나 = True
        for 건 in naite.되돌림_찾기(세션):
            if _우리날짜(건["시각"]) == 날짜:
                잡힌것.append(건)
    return 있었나, 잡힌것


def _우리날짜(시각):
    try:
        t = datetime.fromisoformat(시각.replace("Z", "+00:00"))
    except Exception:
        return None
    return t.astimezone().strftime("%Y-%m-%d")


def 기록_대조(날짜, 글귀):
    """대화 기록에서 그날을 찾아 한 줄로 알려준다 — 참고용이며 합격 여부에 넣지 않는다.

    그날 기록이 아예 없으면 '기록 없음'이다. 이것을 '놓침'이라고 찍으면 기록이
    사라진 것과 규칙이 사고를 놓친 것을 가를 수 없게 된다.
    """
    if not naite.기록_뿌리.exists():
        return "기록 없음 (대화 기록 폴더가 없습니다)"
    있었나, 잡힌것 = 그날_기록(날짜)
    if not 있었나:
        return "기록 없음 (그날 대화 기록이 이미 사라졌습니다)"
    맞은것 = [건 for 건 in 잡힌것 if 글귀 in 건["글"]]
    if 맞은것:
        return f"기록에서도 잡음 · 신호 [{맞은것[0]['신호']}] · 그날 총 {len(잡힌것)}건"
    return f"기록에서는 못 찾음 · 찾던 글귀 \"{글귀}\" · 그날 총 {len(잡힌것)}건"


def 주된흐름(주장=None):
    주장 = sys.argv[1:] if 주장 is None else 주장
    기록도 = "--기록" in 주장

    통과 = 놓침 = 소실 = 0
    print()
    for 이름, 날짜, 교훈번호, 글귀, 원문 in 사고들:
        if 원문 is None:
            소실 += 1
            print(f"  소실   {이름}")
            print(f"         {날짜} · 원문 소실 — 검사 불가")
        else:
            신호 = 원문_판정(원문)
            if 신호:
                통과 += 1
                print(f"  잡음   {이름}")
                print(f"         {날짜} · 신호 [{신호}]")
            else:
                놓침 += 1
                print(f"  놓침   {이름}")
                print(f"         {날짜} · 원문을 넣었는데 판정 규칙이 잡지 못했습니다")
        if 기록도:
            print(f"         {기록_대조(날짜, 글귀)}")
        print(f"         나무 교훈 {교훈번호}")
        print()

    검사한것 = len(사고들) - 소실
    꼬리 = f" (원문 소실로 검사 못 한 {소실}건 제외)" if 소실 else ""
    print(f"  {검사한것}건 중 {통과}건을 짚었습니다{꼬리}.\n")
    return 1 if 놓침 else 0


